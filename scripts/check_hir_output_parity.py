#!/usr/bin/env python3
"""Compare every literal t/t_bytes call in the pinned Rust translator tests.

This verifies exact printed HIR, including all ranges and branch order. It is
not a replacement for structural specs, property tests, or dynamic fixtures.
All generated binaries, caches, and comparison logs live in temp/.
"""
import argparse
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
arguments = argparse.ArgumentParser(description=__doc__)
arguments.add_argument("--write-fixture", action="store_true")
arguments.add_argument("--rust-tests", action="store_true")
options = arguments.parse_args()
os.chdir(ROOT)
TEMP = ROOT / "temp" / "hir-parity"
TEMP.mkdir(parents=True, exist_ok=True)
source = ROOT / "vendor/regex-syntax/src"
revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
if revision != "72d650cb0a880a01ab6dc2137c0888e8f89740f7":
    raise SystemExit(f"Review the upstream refresh before regenerating fixtures: {revision}")
text = (source / "hir/translate.rs").read_text()
pattern = re.compile(
    r'\b(t|t_bytes)\(\s*(r(?P<hashes>\#*)"(?P<raw>.*?)"(?P=hashes)|'
    r'"(?P<str>(?:[^"\\]|\\.)*)")\s*\)', re.S
)
escapes = {"n": "\n", "r": "\r", "t": "\t", "0": "\0", "\\": "\\", '"': '"', "'": "'"}


def decode(value):
    def unescape(match):
        if match[1]:
            return chr(int(match[1].replace("_", ""), 16))
        if match[2]:
            return chr(int(match[2], 16))
        return escapes[match[3]]

    return re.sub(r'\\(?:u\{([0-9a-fA-F_]+)\}|x([0-9a-fA-F]{2})|(.))', unescape, value)

rows = []
for match in pattern.finditer(text):
    value = match["raw"] if match["raw"] is not None else decode(match["str"])
    row = ("bytes" if match[1] == "t_bytes" else "utf8") + "\t" + value.encode().hex()
    if row not in rows:
        rows.append(row)
inputs = "\n".join(rows) + "\n"
(TEMP / "patterns.tsv").write_text(inputs)
features = ["std", "unicode", "unicode-age", "unicode-bool", "unicode-case",
            "unicode-gencat", "unicode-perl", "unicode-script", "unicode-segment"]
command = ["rustc", "--edition=2021", "--crate-type=rlib", "--crate-name=regex_syntax",
           str(source / "lib.rs"), "-o", str(TEMP / "libregex_syntax.rlib")]
for feature in features:
    command += ["--cfg", f'feature="{feature}"']
subprocess.run(command, check=True)
if options.rust_tests:
    test_command = command.copy()
    test_command[test_command.index("--crate-type=rlib")] = "--test"
    test_command[test_command.index("-o") + 1] = str(TEMP / "rust-tests")
    subprocess.run(test_command, check=True)
    subprocess.run([str(TEMP / "rust-tests")], check=True)
subprocess.run(["rustc", "--edition=2021", "scripts/parity/hir_oracle.rs",
                "--extern", f"regex_syntax={TEMP / 'libregex_syntax.rlib'}",
                "-o", str(TEMP / "rust-oracle")], check=True)
rust = subprocess.check_output([str(TEMP / "rust-oracle")], input=inputs, text=True).splitlines()
if len(rust) != len(rows) or "ERROR" in rust:
    raise SystemExit("Rust translator fixtures must all parse successfully and produce one row each")
fixture = ROOT / "spec/fixtures/hir_translate.tsv"
fixture_text = (
    "# Rust regex-syntax 0.8.11; 72d650cb0a880a01ab6dc2137c0888e8f89740f7\n"
    "# Generated by scripts/check_hir_output_parity.py --write-fixture\n"
    "# mode\tpattern_utf8_hex\texpected_display_utf8_hex\n" +
    "\n".join(row + "\t" + expected for row, expected in zip(rows, rust)) + "\n"
)
if options.write_fixture:
    fixture.parent.mkdir(parents=True, exist_ok=True)
    fixture.write_text(fixture_text)
elif fixture.read_text() != fixture_text:
    raise SystemExit("Committed HIR fixtures differ from the pinned Rust oracle")
env = dict(os.environ, CRYSTAL_CACHE_DIR=str(TEMP / "crystal-cache"))
subprocess.run(["crystal", "build", "scripts/parity/hir_oracle.cr", "-o", str(TEMP / "crystal-oracle")],
               env=env, check=True)
crystal = subprocess.check_output([str(TEMP / "crystal-oracle")], input=inputs, text=True).splitlines()
if len(rust) != len(rows) or len(crystal) != len(rows):
    raise SystemExit("Oracle output row count does not match input")
mismatches = []
for row, expected, actual in zip(rows, rust, crystal):
    if expected != actual:
        mode, encoded = row.split("\t")
        print(f"Mismatch ({mode}): {bytes.fromhex(encoded).decode()!r}")
        mismatches.append(row + "\t" + expected + "\t" + actual)
(TEMP / "mismatches.tsv").write_text("\n".join(mismatches))
print(f"{len(rows) - len(mismatches)}/{len(rows)} exact HIR outputs match Rust")
raise SystemExit(bool(mismatches))
